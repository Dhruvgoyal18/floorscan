"""Generate capture/DEVICE_MATRIX.md: which tier runs on which hardware, and the accuracy each tier
delivers, pulled from the benchmark reports (real if present, synthetic otherwise, labelled)."""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

HARDWARE = {
    "lidar": ("iPhone 15 Pro / Pro Max, 16 Pro / Pro Max, 17 Pro / Pro Max; iPad Pro (2020+)",
              "Stray Scanner (free)", "LiDAR depth 256x192 + ARKit poses + intrinsics; no learned model"),
    "video": ("Any iPhone 15 or newer (incl. Pro)", "built-in Camera, 1x, 4K30 or 1080p",
              "MapAnything (Apache-2.0) depth+poses; Depth-Anything-V2 + PnP fallback"),
    "photo": ("Any iPhone 15 or newer (incl. Pro)", "built-in Camera, 0.5x ultra-wide",
              "same backend per room folder; rooms stitched by doorway matching"),
}


def load(name):
    p = ROOT / "reports" / name / "benchmark.json"
    return json.loads(p.read_text()) if p.exists() else None


def cell(s, tier, kind):
    if not s:
        return "pending"
    g = s["gates"]
    if kind == "wall":
        w = g["wall_lengths"].get(tier)
        return f"median {w['median_rel_err_pct']:.2f} %, max {w['max_rel_err_pct']:.1f} %" if w and w["n"] else "-"
    if kind == "ceiling":
        c = g["ceiling_height"].get(tier)
        if not c or not c["rooms"]:
            return "-"
        return f"worst {max(r['max_abs_err_cm'] for r in c['rooms']):.1f} cm"
    if kind == "opening":
        o = g["opening_widths"].get(tier)
        return f"median {o['median_abs_err_cm']:.1f} cm; {o['within_2cm']}/{o['gt_openings'] + o['phantom']} within 2 cm" if o and o["median_abs_err_cm"] is not None else "-"
    if kind == "cov":
        rows = {r["kind"]: r for r in s["calibration"].get(tier, [])}
        r = rows.get("wall_length")
        return f"{r['coverage']:.0%} (n={r['n']})" if r else "-"


def main():
    real, syn = load("real"), load("synthetic")
    L = ["# Device matrix", "",
         "Which tier runs on which hardware, and what accuracy it honestly delivers. Accuracy columns are generated by "
         "`python scripts/device_matrix.py` from the benchmark reports. **Real** = laser/tape-scored captures; "
         "**synthetic** = rendered captures with injected sensor error (video/photo via the oracle stand-in for the "
         "learned backend) - a pipeline check, not a real-world claim.", "",
         "| Tier | Hardware | Capture app | Depth / pose source |", "|---|---|---|---|"]
    for t, (hw, app, src) in HARDWARE.items():
        L.append(f"| {t} | {hw} | {app} | {src} |")
    for label, s in (("Real benchmark", real), ("Synthetic benchmark", syn)):
        L += ["", f"## Accuracy - {label}" + ("" if s else " (not yet run)"), "",
              "| Tier | Wall length error | Ceiling height | Opening width | ci90 coverage (walls, LORO) |", "|---|---|---|---|---|"]
        for t in HARDWARE:
            L.append(f"| {t} | {cell(s, t, 'wall')} | {cell(s, t, 'ceiling')} | {cell(s, t, 'opening')} | {cell(s, t, 'cov')} |")
    L += ["", "## Planning targets (stated before measuring)", "",
          "| Tier | Wall length | Ceiling height | Openings |", "|---|---|---|---|",
          "| LiDAR | ~1 % | < 1.5 cm | < 2 cm on 85 %+ |", "| Video | < 3 % | 3-5 cm | 3-5 cm |", "| Photo | < 8 % | 5-10 cm | 5-10 cm |",
          "", "Known degradations: low light (video/photo blur -> widened intervals), mirrors (detected and removed), glass "
          "(LiDAR passes through; windows found from no-return rays), glossy floors (robust plane fits; floor from the "
          "histogram mode)."]
    (ROOT / "capture" / "DEVICE_MATRIX.md").write_text("\n".join(L) + "\n")
    print((ROOT / "capture" / "DEVICE_MATRIX.md").read_text())


if __name__ == "__main__":
    main()

"""Render benchmark.json into benchmark.md (generated; never edited by hand)."""
from __future__ import annotations

from pathlib import Path


def _f(x, nd=2, pct=False):
    if x is None:
        return "-"
    if isinstance(x, bool):
        return "PASS" if x else "FAIL"
    if isinstance(x, float):
        return f"{x * 100:.{nd}f}%" if pct else f"{x:.{nd}f}"
    return str(x)


def _pf(p):
    return "n/a" if p is None else ("**PASS**" if p else "**FAIL**")


def write_report(s: dict, path: Path, results: dict):
    g = s["gates"]
    L = [f"# Benchmark report", "",
         f"Generated by `python -m eval.run` from `{s['manifest']}` with pipeline `{s['pipeline_version']}`. "
         "Every number below is computed by `eval/`; regenerate with `make benchmark`.", ""]
    if "synthetic" in s["manifest"]:
        L += ["> **Synthetic benchmark.** Captures are rendered by `scan/synth` with injected sensor errors; the "
              "video/photo tiers use the *oracle* backend (ground-truth depth degraded by an assumed error model). "
              "These numbers validate the pipeline end to end; they are **not** claims about real-world accuracy. "
              "Real-capture numbers come from `data/benchmark_real.yaml` once captured.", ""]
    L += ["## Gate summary", "", "| Gate | Tier | Result | Number |", "|---|---|---|---|"]
    for t, o in g["opening_widths"].items():
        L.append(f"| Opening widths (<=2 cm on >=85 %, misses+phantoms count) | {t} | {_pf(o['pass'])} | "
                 f"{o['within_2cm']}/{o['gt_openings'] + o['phantom']} = {_f(o['rate'], 1, True)} "
                 f"(missed {o['missed']}, phantom {o['phantom']}, median err {_f(o['median_abs_err_cm'], 1)} cm) |")
    for t, o in g["ceiling_height"].items():
        worst = max((r["max_abs_err_cm"] for r in o["rooms"]), default=None)
        spread = max((r["spread_cm"] for r in o["rooms"] if r["spread_cm"] is not None), default=None)
        L.append(f"| Ceiling height (<=1.5 cm; repeat spread <=1 cm) | {t} | {_pf(o['pass'])} | worst {_f(worst, 2)} cm, "
                 f"max spread {_f(spread, 2)} cm - *{o['diagnosis']}* |")
    for t, o in g["repeatability"].items():
        if o["rows"]:
            worst = max(r["diff_cm"] for r in o["rows"])
            L.append(f"| Repeatability (<=1 cm or 0.5 % per wall) | {t} | {_pf(o['pass'])} | "
                     f"{sum(r['ok'] for r in o['rows'])}/{len(o['rows'])} wall pairs, worst {worst:.2f} cm |")
    for t, o in g["wall_lengths"].items():
        L.append(f"| Wall lengths (within {o['tolerance_rel'] * 100:.0f} % on >=90 %)"
                 f"{' *(Round-1 threshold assumed)*' if t == 'lidar' else ''} | {t} | {_pf(o['pass'])} | "
                 f"{_f(o['share_within'], 1, True)} within, median {_f(o['median_rel_err_pct'], 2)} %, "
                 f"max {_f(o['max_rel_err_pct'], 2)} % |")
    da = g["drift_ablation"]
    for r in da:
        # the gate: a drift method is applied (not poses as-is) and the on/off ablation is reported
        better = abs(r["footprint_err_pct_on"]) <= abs(r["footprint_err_pct_off"]) + 0.5
        L.append(f"| Drift accountability (method applied + on/off ablation; on not worse than off) | {r['tier']} | {_pf(better)} | "
                 f"footprint err {r['footprint_err_pct_on']:+.2f} % on vs {r['footprint_err_pct_off']:+.2f} % off; "
                 f"loop error {r['loop_closure_error_cm']:.1f} -> {r['loop_closure_error_after_cm']:.2f} cm |")
    ps = g["photo_stitch"]
    for r in ps["rows"]:
        L.append(f"| Photo-tier whole-property stitch | photo | {_pf(r['adjacency_correct'] and r['overlap_m2'] <= 0.05 and abs(r['footprint_rel_err_pct']) <= 8 and r['gt_in_ci90'])} | "
                 f"{r['capture']}: adjacency {'correct' if r['adjacency_correct'] else 'WRONG'}, overlap "
                 f"{r['overlap_m2']:.3f} m2, footprint {r['footprint_rel_err_pct']:+.2f} %, GT in ci90: {r['gt_in_ci90']} |")
    L += ["", "## Calibration (leave-one-room-out, target 90 %)", "",
          "| Tier | Kind | n | Coverage | Median ci90 width | Median abs err | Confident garbage? |", "|---|---|---|---|---|---|---|"]
    for t, rows in s["calibration"].items():
        for r in rows:
            L.append(f"| {t} | {r['kind']} | {r['n']} | {_f(r['coverage'], 0, True)} | {r['median_width']:.4f} | "
                     f"{r['median_abs_err']:.4f} | {'YES' if r['confident_garbage'] else 'no'} |")
    L += ["", f"Fitted factors: `{s['calibration_table']['k']}`; per kind `{s['calibration_table'].get('k_kind', {})}`.", ""]

    L += ["## Opening widths: detail", ""]
    for t, o in g["opening_widths"].items():
        L.append(f"- **{t}**: p90 abs err {_f(o['p90_abs_err_cm'], 1)} cm; missed: {', '.join(o['missed_list']) or 'none'}; "
              f"phantom: {', '.join(o['phantom_list']) or 'none'}")
    L += ["", "## Ceiling height per room", "", "| Tier | Room | Captures | Max abs err (cm) | Bias (cm) | Spread (cm) |",
          "|---|---|---|---|---|---|"]
    for t, o in g["ceiling_height"].items():
        for r in o["rooms"]:
            L.append(f"| {t} | {r['room']} | {r['n']} | {r['max_abs_err_cm']:.2f} | {r['bias_cm']:+.2f} | {_f(r['spread_cm'], 2)} |")
    L += ["", "## Repeatability table", "", "| Tier | Room | Wall | Take A | Take B | A (m) | B (m) | Diff (cm) | Tol (cm) | OK |",
          "|---|---|---|---|---|---|---|---|---|---|"]
    for t, o in g["repeatability"].items():
        for r in o["rows"]:
            L.append(f"| {t} | {r['room']} | {r['wall']} | {r['a'].split('_')[-1]} | {r['b'].split('_')[-1]} | {r['La']:.4f} | "
                     f"{r['Lb']:.4f} | {r['diff_cm']:.2f} | {r['tol_cm']:.2f} | {'yes' if r['ok'] else 'NO'} |")
    L += ["", "## Drift ablation (multi-room)", "",
          "| Capture | Footprint err on / off | Median wall err on / off (cm) | Overlap on / off (m2) | Adjacency on / off | Wall-thickness spread on / off (cm) | Loop error before -> after (cm) |",
          "|---|---|---|---|---|---|---|"]
    for r in da:
        L.append(f"| {r['capture']} | {r['footprint_err_pct_on']:+.2f} % / {r['footprint_err_pct_off']:+.2f} % | "
                 f"{_f(r['median_wall_err_cm_on'])} / {_f(r['median_wall_err_cm_off'])} | {r['overlap_m2_on']:.3f} / {r['overlap_m2_off']:.3f} | "
                 f"{r['adjacency_correct_on']} / {r['adjacency_correct_off']} | {_f(r['wall_thickness_spread_cm_on'])} / "
                 f"{_f(r['wall_thickness_spread_cm_off'])} | {r['loop_closure_error_cm']:.1f} -> {r['loop_closure_error_after_cm']:.2f} |")
    if da:
        L.append("")
        for r in da:
            L.append(f"Plans: [{r['capture']} on]({r['plan_on']}), [off]({r['plan_off']})")
    L += ["", "## Footprint and adjacency", "", "| Capture | Tier | Rooms pred/GT | Net area GT | Pred | ci90 | Err | Overlap m2 |",
          "|---|---|---|---|---|---|---|---|"]
    for f in s["footprint"]:
        L.append(f"| {f['capture']} | {f['tier']} | {f['n_rooms_pred']}/{f['n_rooms_gt']} | {f['gt']:.2f} | {f['pred']:.2f} | "
                 f"[{f['ci90'][0]:.2f}, {f['ci90'][1]:.2f}] | {_f(f['rel_err'], 2, True)} | {f['overlap_m2']:.3f} |")
    for a in s["adjacency"]:
        L.append(f"- {a['capture']}: adjacency {'correct' if a['correct'] else 'WRONG'}"
                 f"{'; missing ' + str(a['missing']) if a['missing'] else ''}{'; extra ' + str(a['extra']) if a['extra'] else ''}")
    L += ["", "## Holdout property (never used during development)", "", "| Tier | Walls within tol | Median wall err | Openings within 2 cm |", "|---|---|---|---|"]
    for t, h in s["holdout"].items():
        L.append(f"| {t} | {_f(h['walls']['share_within'], 1, True)} | {_f(h['walls']['median_rel_err_pct'], 2)} % | "
                 f"{h['openings']['within_2cm']}/{h['openings']['gt_openings'] + h['openings']['phantom']} |")
    L += ["", "## Damage", "", "| Capture | GT regions | Found | Class correct | Area err | Missed | False positives |", "|---|---|---|---|---|---|---|"]
    for d in s["damage"]:
        found = d.get("found", [])
        cc = sum(f["gt_class"] == f["pred_class"] for f in found)
        aerr = ", ".join(f"{f['gt_class']}: {(f['pred_area'] / f['gt_area'] - 1) * 100:+.0f}%" for f in found
                         if f["gt_class"] != "crack" and f["gt_area"] > 0)
        L.append(f"| {d['capture']} | {d['gt']} | {len(found)} | {cc}/{len(found)} | {aerr or '-'} | "
                 f"{', '.join(d.get('missed', [])) or '-'} | {len(d.get('false_positive', []))} |")
    L += ["", "## Head-to-head vs consumer app", "",
          "Pending real captures: requires the competitor's export on two benchmark rooms (`data/exports/<app>/`). "
          "The table is generated by `eval/head_to_head.py` from those files." if "synthetic" in s["manifest"] else "", ""]
    L += ["## Timing (seconds, this machine)", "", "| Capture | Tier | Total | Geometry | Damage | Stitch |", "|---|---|---|---|---|---|"]
    for t in s["timing"]:
        L.append(f"| {t['capture']} | {t['tier']} | {t.get('total', 0):.1f} | {t.get('geometry', 0):.1f} | "
                 f"{t.get('damage', 0):.1f} | {t.get('stitch', 0):.1f} |")
    path.write_text("\n".join(L) + "\n")

"""Before/after table for the fix loop: every gate, both runs (generated)."""
from __future__ import annotations

import json
import sys


def gate_rows(s):
    g = s["gates"]
    rows = []
    for t, o in g["opening_widths"].items():
        rows.append((f"opening widths <=2 cm ({t})", f"{o['within_2cm']}/{o['gt_openings'] + o['phantom']} = {o['rate']:.1%}",
                     o["pass"], f"median {o['median_abs_err_cm']:.2f} cm, p90 {o['p90_abs_err_cm']:.2f} cm" if o["median_abs_err_cm"] is not None else ""))
    for t, o in g["ceiling_height"].items():
        worst = max((r["max_abs_err_cm"] for r in o["rooms"]), default=float("nan"))
        spread = max((r["spread_cm"] for r in o["rooms"] if r["spread_cm"] is not None), default=float("nan"))
        rows.append((f"ceiling height ({t})", f"worst {worst:.2f} cm, spread {spread:.2f} cm", o["pass"], o["diagnosis"]))
    for t, o in g["repeatability"].items():
        if o["rows"]:
            rows.append((f"repeatability ({t})", f"{sum(r['ok'] for r in o['rows'])}/{len(o['rows'])}", o["pass"],
                         f"worst {max(r['diff_cm'] for r in o['rows']):.2f} cm"))
    for t, o in g["wall_lengths"].items():
        rows.append((f"wall lengths ({t})", f"{o['share_within']:.1%} within {o['tolerance_rel']:.0%}", o["pass"],
                     f"median {o['median_rel_err_pct']:.2f} %"))
    for r in g["drift_ablation"]:
        rows.append((f"drift ablation ({r['capture']})", f"{r['footprint_err_pct_on']:+.2f} % vs {r['footprint_err_pct_off']:+.2f} % off",
                     abs(r["footprint_err_pct_on"]) <= abs(r["footprint_err_pct_off"]), ""))
    for r in g["photo_stitch"]["rows"]:
        ok = r["adjacency_correct"] and r["overlap_m2"] <= 0.05 and abs(r["footprint_rel_err_pct"]) <= 8 and r["gt_in_ci90"]
        rows.append((f"photo stitch ({r['capture']})", f"adjacency {'ok' if r['adjacency_correct'] else 'wrong'}, "
                     f"footprint {r['footprint_rel_err_pct']:+.2f} %", ok, ""))
    return rows


def main(b, a):
    B, A = json.load(open(b)), json.load(open(a))
    rb, ra = gate_rows(B), gate_rows(A)
    da = {r[0]: r for r in ra}
    print(f"# Fix loop: before vs after\n\nbefore = `{B['pipeline_version']}`, after = `{A['pipeline_version']}` "
          "(both regenerated by `make fixloop` from the same raw data)\n")
    print("| Gate | Before | Pass | After | Pass | Note (after) |\n|---|---|---|---|---|---|")
    pf = lambda p: "n/a" if p is None else ("PASS" if p else "FAIL")  # noqa: E731
    for name, val, p, _ in rb:
        x = da.get(name, (name, "-", None, ""))
        print(f"| {name} | {val} | {pf(p)} | {x[1]} | {pf(x[2])} | {x[3]} |")


if __name__ == "__main__":
    main(*sys.argv[1:3])
